//! Writes the port map as markdown. The text has no date and no absolute path, so the
//! same inputs always give the same bytes.

use std::fmt::Write;

use crate::upstream::SAT_FOLDER;

const GROUP_SIZE: usize = 3;
const NOT_APPLICABLE: &str = "-";
const NO_TEST_FILE: &str = "none";

pub struct Totals {
    pub sat_files: usize,
    pub sat_lines: usize,
    pub test_files: usize,
    pub test_lines: usize,
    pub test_cases: usize,
    pub closure_files: usize,
    pub closure_lines: usize,
    pub sat_cc_files: usize,
    pub sat_cc_with_test: usize,
}

pub struct PhaseCounts {
    pub phase: u32,
    pub ignored: usize,
    pub pending: usize,
}

pub struct Row {
    pub folder: String,
    pub path: String,
    pub lines: usize,
    pub test: Option<String>,
    pub cases: Option<usize>,
    pub includes: Vec<String>,
    pub depth: usize,
    pub phase: Option<u32>,
    pub status: &'static str,
}

pub struct Map {
    pub totals: Totals,
    pub phases: Vec<PhaseCounts>,
    pub rows: Vec<Row>,
}

/// `200923` as `200,923`.
fn grouped(number: usize) -> String {
    let digits = number.to_string();
    let groups: Vec<&str> = digits
        .as_bytes()
        .rchunks(GROUP_SIZE)
        .rev()
        .map(|group| std::str::from_utf8(group).unwrap_or_default())
        .collect();
    groups.join(",")
}

fn code_list(paths: &[String]) -> String {
    if paths.is_empty() {
        return NOT_APPLICABLE.to_string();
    }
    paths
        .iter()
        .map(|path| format!("`{path}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

pub fn render(map: &Map) -> String {
    let totals = &map.totals;
    let mut out = String::new();
    // Writing to a String cannot fail.
    let _ = write!(
        out,
        "# Port map\n\n\
         Generated by `cargo xtask port-map`. Do not edit by hand.\n\n\
         ## Totals\n\n\
         | Item | Files | Lines | Cases |\n|---|---|---|---|\n\
         | `{SAT_FOLDER}` files, tests not counted | {} | {} | {NOT_APPLICABLE} |\n\
         | `{SAT_FOLDER}` test files | {} | {} | {} |\n\
         | Include closure of `{SAT_FOLDER}`, tests not counted | {} | {} | {NOT_APPLICABLE} |\n\n\
         Non-test `.cc` files of `{SAT_FOLDER}`: {}. With a test file: {}. Without a test file: {}.\n\n\
         ## Ignored tests and pending lines by phase\n\n\
         | Phase | Ignored tests | Pending lines |\n|---|---|---|\n",
        grouped(totals.sat_files),
        grouped(totals.sat_lines),
        grouped(totals.test_files),
        grouped(totals.test_lines),
        grouped(totals.test_cases),
        grouped(totals.closure_files),
        grouped(totals.closure_lines),
        totals.sat_cc_files,
        totals.sat_cc_with_test,
        totals.sat_cc_files - totals.sat_cc_with_test,
    );
    for phase in &map.phases {
        let _ = writeln!(
            out,
            "| {} | {} | {} |",
            phase.phase, phase.ignored, phase.pending
        );
    }
    out.push_str(
        "\n## Files\n\n\
         | Folder | File | Lines | Test file | Cases | Includes | Depth | Phase | Status |\n\
         |---|---|---|---|---|---|---|---|---|\n",
    );
    for row in &map.rows {
        let test = row
            .test
            .as_ref()
            .map_or(NO_TEST_FILE.to_string(), |test| format!("`{test}`"));
        let cases = row
            .cases
            .map_or(NOT_APPLICABLE.to_string(), |cases| cases.to_string());
        let phase = row
            .phase
            .map_or(NOT_APPLICABLE.to_string(), |phase| phase.to_string());
        let _ = writeln!(
            out,
            "| {} | `{}` | {} | {} | {} | {} | {} | {} | {} |",
            row.folder,
            row.path,
            row.lines,
            test,
            cases,
            code_list(&row.includes),
            row.depth,
            phase,
            row.status,
        );
    }
    out
}
